CREATE TABLE games (
  id VARCHAR(32) PRIMARY KEY,
  title VARCHAR(512) NOT NULL,
  steam_app_id VARCHAR(32),
  thumbnail VARCHAR(2048),
  review_percent INTEGER NOT NULL DEFAULT 0,
  review_count INTEGER NOT NULL DEFAULT 0,
  review_text VARCHAR(128)
);
CREATE TABLE offers (
  id VARCHAR(64) PRIMARY KEY,
  game_id VARCHAR(32) NOT NULL REFERENCES games(id),
  store_id VARCHAR(16) NOT NULL,
  deal_id VARCHAR(512) NOT NULL,
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  regular_price NUMERIC(12,2) NOT NULL CHECK (regular_price >= 0),
  discount INTEGER NOT NULL,
  deal_rating NUMERIC(5,2) NOT NULL,
  active BOOLEAN NOT NULL,
  checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(game_id, store_id)
);
CREATE INDEX idx_offers_game ON offers(game_id, active);
CREATE TABLE price_observations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id VARCHAR(32) NOT NULL REFERENCES games(id),
  store_id VARCHAR(16) NOT NULL,
  price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  observed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_history_game ON price_observations(game_id, observed_at);
CREATE TABLE wishlist (
  id VARCHAR(80) PRIMARY KEY,
  profile_id VARCHAR(36) NOT NULL,
  game_id VARCHAR(32) NOT NULL REFERENCES games(id),
  target_price NUMERIC(12,2),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE(profile_id, game_id)
);
CREATE INDEX idx_wishlist_profile ON wishlist(profile_id);
CREATE TABLE sync_state (
  id VARCHAR(16) PRIMARY KEY,
  last_success TIMESTAMP WITH TIME ZONE,
  last_attempt TIMESTAMP WITH TIME ZONE,
  last_error VARCHAR(512)
);
